import { describe, expect, it } from "vitest";
import { createSampleDocument } from "../editor/domain";
import { indexLegacyProject } from "./packDocument";
import { makeIndexedJava1214Pack } from "./javaPackBuilder";
import { inspectIndexedJava1214Pack, planIndexedJava1214Pack } from "./exportPreflight";

const clone = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;

describe("indexed pack export preflight", () => {
  it("previews the exact generated ZIP paths, owners and two affected vanilla blocks", () => {
    const first = createSampleDocument();
    const second = { ...createSampleDocument(), id: "preview-second", name: "Iron source" };
    const pack = clone(indexLegacyProject(first));
    pack.models.push({
      id: "model-iron", sourceDocumentId: second.id,
      resource: { namespace: "tester", path: "block/iron_model" },
      replaces: { namespace: "minecraft", path: "iron_block" },
      provenance: "editor",
      textures: [{ sourceTextureId: "main", textureAssetId: "iron-texture" }]
    });
    pack.textures.push({
      id: "iron-texture", sourceDocumentId: second.id, sourceTextureId: "main",
      resource: { namespace: "tester", path: "block/iron_paint" }
    });
    const snapshot = JSON.stringify({ pack, sources: [first, second] });
    const plan = planIndexedJava1214Pack(pack, [first, second]);
    const exported = makeIndexedJava1214Pack(pack, [first, second]);
    expect(plan.issues.filter(issue => issue.severity === "error")).toEqual([]);
    expect(plan.replacements).toEqual(["minecraft:diamond_block", "minecraft:iron_block"]);
    expect(plan.files.map(file => file.path)).toEqual(exported.paths);
    expect(plan.files[0]).toEqual({ path: "pack.mcmeta", kind: "metadata" });
    expect(plan.files.find(file => file.path === "assets/tester/models/block/iron_model.json"))
      .toEqual({ path: "assets/tester/models/block/iron_model.json", kind: "model",
        sourceDocumentId: second.id, sourceName: "Iron source" });
    expect(plan.files.some(file => file.path ===
      "assets/tester/textures/block/iron_model/solid_1.png")).toBe(true);
    expect(JSON.stringify({ pack, sources: [first, second] })).toBe(snapshot);
  });

  it("marks generated collisions as blockers instead of offering a misleading file preview", () => {
    const source = createSampleDocument();
    const pack = clone(indexLegacyProject(source));
    pack.textures[0]!.resource.path = "block/solid_1";
    const plan = planIndexedJava1214Pack(pack, [source]);
    expect(plan.issues.some(issue =>
      issue.severity === "error" && issue.code === "RESOURCE_PATH_COLLISION")).toBe(true);
    expect(plan.files.filter(file =>
      file.path === "assets/3dmc/textures/block/solid_1.png")).toHaveLength(2);
    expect(inspectIndexedJava1214Pack(pack, [source])).toEqual(plan.issues);
  });

  it("shows one correct replacement-scope warning without changing source data", () => {
    const source = createSampleDocument();
    const index = indexLegacyProject(source);
    const original = JSON.stringify({ index, source });
    const issues = inspectIndexedJava1214Pack(index, [source]);
    expect(issues.filter(issue => issue.severity === "error")).toEqual([]);
    expect(issues.filter(issue => issue.code === "PACK_VISUAL_REPLACEMENTS_ONLY")).toHaveLength(1);
    expect(issues.find(issue => issue.code === "PACK_VISUAL_REPLACEMENTS_ONLY")?.message)
      .toContain("minecraft:diamond_block");
    expect(JSON.stringify({ index, source })).toBe(original);
    expect(makeIndexedJava1214Pack(index, [source]).zip.length).toBeGreaterThan(100);
  });

  it("blocks generated solid/texture destination collisions before ZIP construction", () => {
    const source = createSampleDocument();
    const index = clone(indexLegacyProject(source));
    index.textures[0]!.resource.path = "block/solid_1"; // Generated by Foundation.
    const issues = inspectIndexedJava1214Pack(index, [source]);
    const collision = issues.find(issue => issue.code === "RESOURCE_PATH_COLLISION");
    expect(collision?.severity).toBe("error");
    expect(collision?.message).toContain("assets/3dmc/textures/block/solid_1.png");
    expect(collision?.message).toContain("Pack Studio");
    expect(() => makeIndexedJava1214Pack(index, [source])).toThrow(/Generated resource path collision/);
  });

  it("identifies the correct source model and uses the supported target registry", () => {
    const first = createSampleDocument();
    const second = { ...createSampleDocument(), id: "second-source", name: "Secondary Model",
      cuboids: createSampleDocument().cuboids.map((node, index) => index === 0 ? {
        ...node, from: [40, 3, 3] as const, to: [50, 12, 13] as const
      } : node) };
    const index = clone(indexLegacyProject(first));
    index.models.push({
      id: "model-two", sourceDocumentId: second.id,
      resource: { namespace: "my_pack", path: "block/second" },
      replaces: { namespace: "minecraft", path: "iron_block" },
      textures: [{ sourceTextureId: "main", textureAssetId: "texture-two" }],
      provenance: "editor"
    });
    index.textures.push({
      id: "texture-two", sourceDocumentId: second.id, sourceTextureId: "main",
      resource: { namespace: "my_pack", path: "block/second_paint" }
    });
    const issues = inspectIndexedJava1214Pack(index, [first, second]);
    expect(issues.find(issue => issue.code === "ELEMENT_BOUNDS")).toMatchObject({
      sourceDocumentId: "second-source", sourceName: "Secondary Model", nodeId: "body"
    });
    const scope = issues.find(issue => issue.code === "PACK_VISUAL_REPLACEMENTS_ONLY")!;
    expect(scope.message).toContain("minecraft:diamond_block");
    expect(scope.message).toContain("minecraft:iron_block");
    expect(issues.filter(issue => issue.code === "PACK_GAME_CHECK_REQUIRED")).toHaveLength(1);

    index.models[1]!.replaces.path = "oak_log"; // Needs axis variants.
    expect(inspectIndexedJava1214Pack(index, [first, second])
      .find(issue => issue.code === "UNSUPPORTED_BLOCK_REPLACEMENT")).toMatchObject({
        severity: "error", sourceDocumentId: "second-source"
      });
  });

  it("turns malformed pack references into blockers rather than partial exports", () => {
    const doc = createSampleDocument();
    const index = clone(indexLegacyProject(doc));
    index.models[0]!.textures[0]!.textureAssetId = "missing";
    expect(inspectIndexedJava1214Pack(index, [doc])).toMatchObject([{
      code: "PACK_SOURCE_INVALID", severity: "error"
    }]);
    const restored = indexLegacyProject(doc);
    expect(inspectIndexedJava1214Pack(restored, [])
      .find(issue => issue.code === "PACK_SOURCE_INVALID")).toBeDefined();
  });
});
